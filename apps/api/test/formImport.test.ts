import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { formContexts, formConditionSchema, formSchemaValidator, formAllowsRecords, isFormFieldVisible, visibleFormValues, validateFormValues, list20Position, renumberList20, canonicalFormJson, executionFormDataSchema } from '@toce/shared';
import { planFormImport, type FormTarget } from '../src/lib/formImport.js';
import { readWorkbook } from '../src/lib/templateImport.js';

const bytes = await readFile(new URL('./fixtures/forms/TOCE_24_metodos.xlsx', import.meta.url));
const catalog = JSON.parse((await readFile(new URL('./fixtures/forms/catalog.json', import.meta.url),'utf8')).replace(/^\uFEFF/,'')) as Record<string,string>[];
const targets: FormTarget[] = catalog.map((c) => ({ id: randomUUID(), code: c['Código']!, specialtyCode: c.Especialidad!, specialtyName: c.Especialidad!, formSchema: { fields: [{ key: 'anterior', label: 'Anterior', type: 'text' }] } }));
const plan = await planFormImport(bytes, targets);
assert.deepEqual(plan.errors, [], plan.errors.join('\n'));
assert.equal(plan.items.length, 24);
assert.equal(plan.items.reduce((n,i) => n+i.after.fields.length,0),221);
const get = (code: string) => plan.items.find((i) => i.code === code)!.after;
for (const code of ['BBA','BSN','PFC','PFS','PAN','RED','TIV','RAP','CT']) assert(!plan.items.some((i) => i.code === code));
assert(!get('SH').fields.some((f) => f.key === 'cebo'));
assert(get('TH').fields.some((f) => f.key === 'cebo'));
assert(!get('PI').fields.some((f) => /altura|dap|orientacion/.test(f.key)));
assert.equal(formContexts(get('PI')).length,100);
assert.equal(formContexts(get('PI'))[99]!.values.distancia,50);
assert.equal(formContexts(get('EPN')).length,6);
assert.equal(formContexts(get('PFO')).filter((x) => x.values.categoria === 'brinzal').length,5);
const surface = get('PI').fields.find((f) => f.key === 'superficie')!;
assert(isFormFieldVisible(surface,{estado_punto:'sin_vegetacion'}));
assert(!isFormFieldVisible(surface,{estado_punto:'con_vegetacion'}));
assert(!formAllowsRecords({estado_punto:'no_evaluado'}));
assert(!formAllowsRecords({resultado_busqueda:'sin_hallazgos'}));
const visible = visibleFormValues(get('PI').fields, {estado_punto:'con_vegetacion',superficie:'otra',otra_superficie:'arena'});
assert(!('otra_superficie' in visible));
assert.equal(Object.keys(validateFormValues([surface],{estado_punto:'con_vegetacion'})).length,0);
assert(validateFormValues([surface],{estado_punto:'sin_vegetacion'}).superficie);
assert(!formConditionSchema.safeParse({run:'process.exit()'}).success);
assert.equal(list20Position('sp A',[{values:{especie:'sp A'}},{values:{especie:'sp B'}}]),1);
assert.equal(list20Position('sp C',[{values:{especie:'sp A'}},{values:{especie:'sp B'}}]),3);
assert.deepEqual(renumberList20([{values:{especie:'sp B'}},{values:{especie:'sp B'}},{values:{especie:'sp C'}}]).map((r)=>r.values.posicion_lista),[1,1,2]);
assert.equal(canonicalFormJson({a:1,b:{x:2,y:3}}),canonicalFormJson({b:{y:3,x:2},a:1}));
assert(!formSchemaValidator.safeParse({fields:[{key:'a',label:'A',type:'text',visibleIf:{'==':[{var:'b'},'x']}},{key:'b',label:'B',type:'text',visibleIf:{'==':[{var:'a'},'x']}}]}).success);
assert(validateFormValues([{key:'cobertura',label:'Cobertura',type:'number',min:0,max:100}],{cobertura:101}).cobertura);
assert(validateFormValues([{key:'coords',label:'Coordenadas',type:'coords'}],{coords:{lat:91,lng:0}}).coords);
assert(validateFormValues([{key:'fecha',label:'Fecha',type:'date'}],{fecha:'2026-02-30'}).fecha);
assert.deepEqual(validateFormValues([{key:'fecha',label:'Fecha',type:'date'}],{fecha:'2026-11-26'}),{});
const data = { records: [{id:randomUUID(),createdAt:new Date().toISOString(),values:{especie:'sp A'},contextId:'1',group:'registros'}], header: {resultado:'con_registros'}, contexts:{'1':{numero_punto:1}},schemaSnapshot:get('PI') };
assert.deepEqual(executionFormDataSchema.parse(data),data);
assert.equal((await planFormImport(bytes,targets)).fingerprint,plan.fingerprint);
assert.notEqual((await planFormImport(bytes,targets.map((t) => ({...t,formSchema:{fields:[]}})))).fingerprint,plan.fingerprint);
const ambiguous = await planFormImport(bytes,[...targets,{...targets.find((t)=>t.code==='PI')!,id:randomUUID()}]);
assert(ambiguous.errors.some((e)=>e.includes('exactamente')));
const wb = await readWorkbook(bytes);
wb.getWorksheet('Campos')!.getCell('J2').value = '{"run":"malicious"}';
const broken = await planFormImport(Buffer.from(await wb.xlsx.writeBuffer()), targets);
assert(broken.errors.length > 0);
wb.getWorksheet('Campos')!.getCell('J2').value = '';
wb.getWorksheet('Campos')!.getCell('H5').value = 'lista_inexistente';
assert((await planFormImport(Buffer.from(await wb.xlsx.writeBuffer()), targets)).errors.some((e)=>e.includes('lista_inexistente')));
console.log('PASS: 24 métodos / 221 campos; exclusiones, tipos, condiciones, niveles, límites, versiones y errores de importación.');
